import { describe, expect, test } from 'bun:test'
import { formatFromFileName, parseNuspec, parsePkgInfo, squirrelArchFromFileName } from '../src/detect'

describe('formatFromFileName', () => {
  test.each([
    ['app-1.0-1-x86_64.pkg.tar.zst', 'arch'],
    ['app-1.0-1-any.pkg.tar.xz', 'arch'],
    ['app_1.0_amd64.deb', 'deb'],
    ['app-1.0-1.x86_64.rpm', 'rpm'],
    ['App-1.0.0-full.nupkg', 'squirrel'],
    ['App-1.0.0-DELTA.NUPKG', 'squirrel'],
    ['app-1.0-1.src.rpm', null],
    ['app-1.0-1-x86_64.pkg.tar.zst.sig', null],
    ['app.AppImage', null],
    ['RELEASES', null],
  ])('%s', (name, format) => {
    expect(formatFromFileName(name)).toBe(format as ReturnType<typeof formatFromFileName>)
  })
})

describe('squirrelArchFromFileName', () => {
  test.each([
    ['App-1.0.0-full.nupkg', 'x64'],
    ['App-1.0.0-x64-full.nupkg', 'x64'],
    ['App-1.0.0-arm64-full.nupkg', 'arm64'],
    ['App_1.0.0_ia32-delta.nupkg', 'x86'],
    ['App-win32-1.0.0-full.nupkg', 'x86'],
  ])('%s', (name, arch) => {
    expect(squirrelArchFromFileName(name)).toBe(arch)
  })
})

describe('parsePkgInfo', () => {
  test('reads the first value of each field', () => {
    const text = `# Generated by makepkg
pkgname = app
pkgbase = app
pkgver = 1.2-3
arch = x86_64
depend = glibc
depend = zlib
`
    expect(parsePkgInfo(text)).toEqual({ name: 'app', version: '1.2-3', arch: 'x86_64' })
  })

  test('requires the core fields', () => {
    expect(() => parsePkgInfo('pkgname = app\n')).toThrow(/pkgver/)
  })
})

describe('parseNuspec', () => {
  test('reads id and version', () => {
    const xml = `<?xml version="1.0"?>
<package xmlns="http://schemas.microsoft.com/packaging/2010/07/nuspec.xsd">
  <metadata>
    <id> MyApp </id>
    <version>1.2.3</version>
  </metadata>
</package>`
    expect(parseNuspec(xml)).toEqual({ id: 'MyApp', version: '1.2.3' })
  })
})
